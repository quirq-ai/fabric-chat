// Writes the network's configuration files from network.json into .generated/.
// Usage: node network/generate.mjs
//
// One company in network.json becomes: a peer (with its CouchDB state database), a Raft orderer, a
// certificate authority and a chaincode container. One workspace becomes one Fabric channel.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, ".generated");
const net = JSON.parse(fs.readFileSync(path.join(root, "network.json"), "utf8"));

const title = (text) => text[0].toUpperCase() + text.slice(1);

for (const o of net.orgs) {
  // The code becomes part of host names and of the MSP ID. Scope names join MSP IDs with "-", so no dashes.
  if (!/^[a-z][a-z0-9]{1,15}$/.test(o.code)) throw new Error(`Company code "${o.code}" must be 2 to 16 lower-case letters or digits.`);
  for (const p of o.people) {
    if (!/^[a-z0-9][a-z0-9._-]{0,31}$/.test(p.id)) throw new Error(`Person id "${p.id}" must be lower-case letters, digits, dot, dash or underscore.`);
  }
}
for (const w of net.workspaces) {
  if (!/^[a-z][a-z0-9-]{1,40}$/.test(w.channel)) throw new Error(`Channel name "${w.channel}" must be lower-case letters, digits or dashes.`);
}

const cc = net.chaincode.name;
// Orderers talk to peers and apps on 7050. With ports.cluster set, they talk to each other on a
// second port that insists on a certificate from both ends. Two orderers that start separately, as
// two companies' do, need this: without it, a link made before the other side knows the channel is
// made without a certificate, and Fabric keeps using that link.
const clusterPort = net.ports.cluster ?? 7050;
const orgs = net.orgs.map((o, i) => {
  const domain = `${o.code}.${net.domain}`;
  const ordererDomain = `ord-${o.code}.${net.domain}`;
  return {
    ...o,
    msp: `${title(o.code)}MSP`,
    ordererMsp: `${title(o.code)}OrdererMSP`,
    domain,
    ordererDomain,
    peer: `peer0.${domain}`,
    couch: `couchdb0.${domain}`,
    orderer: `orderer0.${ordererDomain}`,
    ca: `ca.${domain}`,
    chaincode: `${cc}.${domain}`,
    peerPort: net.ports.peer + i * 10,
    couchPort: net.ports.couchdb + i,
  };
});
const byCode = new Map(orgs.map((o) => [o.code, o]));

const workspaces = net.workspaces.map((w) => {
  const members = w.orgs.map((code) => {
    const org = byCode.get(code);
    if (!org) throw new Error(`Workspace ${w.channel} names an unknown company: ${code}`);
    return org;
  });
  // With three or more companies, every pair gets a private data collection: a place only those two
  // companies' peers store. With two companies the whole channel is already just the pair.
  const pairs = members.length > 2 ? members.flatMap((a, i) => members.slice(i + 1).map((b) => [a, b])) : [];
  return {
    ...w,
    members,
    collections: pairs.map(([a, b]) => ({ name: `${a.msp}-${b.msp}`, orgs: [a.code, b.code], msps: [a.msp, b.msp] })),
  };
});

// Passwords made once per network and kept in .generated, which is never committed.
fs.mkdirSync(out, { recursive: true });
const secretsFile = path.join(out, "secrets.json");
if (!fs.existsSync(secretsFile)) {
  fs.writeFileSync(
    secretsFile,
    JSON.stringify({ couchdb: crypto.randomBytes(16).toString("hex"), registrar: crypto.randomBytes(16).toString("hex") }, null, 2) + "\n",
  );
}
const secrets = JSON.parse(fs.readFileSync(secretsFile, "utf8"));

/* ------------------------------------------------------------------ crypto-config.yaml */

const cryptoConfig = [
  "# Generated by network/generate.mjs. Read by cryptogen to make each node's test certificates.",
  "OrdererOrgs:",
  ...orgs.flatMap((o) => [
    `  - Name: ${title(o.code)}Orderer`,
    `    Domain: ${o.ordererDomain}`,
    "    EnableNodeOUs: true",
    "    Specs:",
    "      - Hostname: orderer0",
  ]),
  "PeerOrgs:",
  ...orgs.flatMap((o) => [
    `  - Name: ${title(o.code)}`,
    `    Domain: ${o.domain}`,
    "    EnableNodeOUs: true",
    "    Template:",
    "      Count: 1",
    // The app reaches each peer through a port published on this machine, so the TLS certificate names localhost too.
    "      SANS:",
    "        - localhost",
    "        - 127.0.0.1",
    "    Users:",
    "      Count: 1",
  ]),
  "",
].join("\n");

/* ------------------------------------------------------------------ configtx.yaml */

const implicit = (rule) => `{ Type: ImplicitMeta, Rule: "${rule}" }`;
const signature = (rule) => `{ Type: Signature, Rule: "${rule}" }`;

const ordererOrg = (o, pad) =>
  [
    `- Name: ${title(o.code)}Orderer`,
    `  ID: ${o.ordererMsp}`,
    `  MSPDir: crypto-config/ordererOrganizations/${o.ordererDomain}/msp`,
    "  Policies:",
    `    Readers: ${signature(`OR('${o.ordererMsp}.member')`)}`,
    `    Writers: ${signature(`OR('${o.ordererMsp}.member')`)}`,
    `    Admins: ${signature(`OR('${o.ordererMsp}.admin')`)}`,
    "  OrdererEndpoints:",
    `    - ${o.orderer}:7050`,
  ].map((line) => pad + line);

const peerOrg = (o, pad) =>
  [
    `- Name: ${title(o.code)}`,
    `  ID: ${o.msp}`,
    `  MSPDir: crypto-config/peerOrganizations/${o.domain}/msp`,
    "  Policies:",
    `    Readers: ${signature(`OR('${o.msp}.admin', '${o.msp}.peer', '${o.msp}.client')`)}`,
    `    Writers: ${signature(`OR('${o.msp}.admin', '${o.msp}.client')`)}`,
    `    Admins: ${signature(`OR('${o.msp}.admin')`)}`,
    // What "this company endorsed it" means: a signature from one of its peers.
    `    Endorsement: ${signature(`OR('${o.msp}.peer')`)}`,
    // Anchor peers go into the channel's first block, so peers of different companies find each other at once.
    "  AnchorPeers:",
    `    - Host: ${o.peer}`,
    "      Port: 7051",
  ].map((line) => pad + line);

const tlsCert = (o) => `crypto-config/ordererOrganizations/${o.ordererDomain}/orderers/${o.orderer}/tls/server.crt`;

// One profile per workspace. Fabric 2.5 has no system channel: each profile is a complete channel,
// and its first block is what orderers and peers are handed to join it.
const profile = (w) => [
  `  ${w.channel}:`,
  "    Policies:",
  `      Readers: ${implicit("ANY Readers")}`,
  `      Writers: ${implicit("ANY Writers")}`,
  `      Admins: ${implicit("MAJORITY Admins")}`,
  "    Capabilities: { V2_0: true }",
  "    Orderer:",
  `      OrdererType: ${net.consensus.type}`,
  `      BatchTimeout: ${net.consensus.batchTimeout}`,
  "      BatchSize:",
  `        MaxMessageCount: ${net.consensus.maxMessageCount}`,
  `        AbsoluteMaxBytes: ${net.consensus.absoluteMaxBytes}`,
  `        PreferredMaxBytes: ${net.consensus.preferredMaxBytes}`,
  "      EtcdRaft:",
  // Only the member companies' orderers order this channel. An orderer sees every transaction it
  // orders, so a company that is not in the workspace must not be one of them.
  "        Consenters:",
  ...w.members.flatMap((o) => [
    `          - Host: ${o.orderer}`,
    `            Port: ${clusterPort}`,
    `            ClientTLSCert: ${tlsCert(o)}`,
    `            ServerTLSCert: ${tlsCert(o)}`,
  ]),
  "      Organizations:",
  ...w.members.flatMap((o) => ordererOrg(o, "        ")),
  "      Policies:",
  `        Readers: ${implicit("ANY Readers")}`,
  `        Writers: ${implicit("ANY Writers")}`,
  `        Admins: ${implicit("MAJORITY Admins")}`,
  `        BlockValidation: ${implicit("ANY Writers")}`,
  "      Capabilities: { V2_0: true }",
  "    Application:",
  "      Organizations:",
  ...w.members.flatMap((o) => peerOrg(o, "        ")),
  "      Policies:",
  `        Readers: ${implicit("ANY Readers")}`,
  `        Writers: ${implicit("ANY Writers")}`,
  `        Admins: ${implicit("MAJORITY Admins")}`,
  // More than half of the companies must approve a chaincode before it runs, and more than half must
  // endorse a transaction before it counts.
  `        LifecycleEndorsement: ${implicit("MAJORITY Endorsement")}`,
  `        Endorsement: ${implicit("MAJORITY Endorsement")}`,
  // V2_5 turns on purging of private data, which "delete" uses in private conversations.
  "      Capabilities: { V2_5: true }",
];

const configtx = [
  "# Generated by network/generate.mjs. Read by configtxgen to make each channel's first block.",
  "Profiles:",
  ...workspaces.flatMap(profile),
  "",
].join("\n");

/* ------------------------------------------------------------------ private data collections */

const collectionsOf = (w) =>
  w.collections.map((c) => ({
    name: c.name,
    policy: `OR(${c.msps.map((m) => `'${m}.member'`).join(",")})`,
    // Both companies endorse every private transaction, so both already hold the data when it commits.
    requiredPeerCount: 0,
    maxPeerCount: 1,
    blockToLive: 0,
    memberOnlyRead: true,
    memberOnlyWrite: true,
  }));

/* ------------------------------------------------------------------ docker-compose.yaml */

const list = (items, pad) => items.map((item) => `${pad}- ${item}`);

const ordererService = (o) => {
  const base = `./crypto-config/ordererOrganizations/${o.ordererDomain}/orderers/${o.orderer}`;
  const tls = "/var/hyperledger/orderer/tls";
  return [
    `  ${o.orderer}:`,
    `    container_name: ${o.orderer}`,
    `    image: hyperledger/fabric-orderer:${net.fabric.version}`,
    "    restart: unless-stopped",
    "    environment:",
    ...list(
      [
        "FABRIC_LOGGING_SPEC=INFO",
        "ORDERER_GENERAL_LISTENADDRESS=0.0.0.0",
        "ORDERER_GENERAL_LISTENPORT=7050",
        `ORDERER_GENERAL_LOCALMSPID=${o.ordererMsp}`,
        "ORDERER_GENERAL_LOCALMSPDIR=/var/hyperledger/orderer/msp",
        "ORDERER_GENERAL_TLS_ENABLED=true",
        `ORDERER_GENERAL_TLS_PRIVATEKEY=${tls}/server.key`,
        `ORDERER_GENERAL_TLS_CERTIFICATE=${tls}/server.crt`,
        `ORDERER_GENERAL_TLS_ROOTCAS=[${tls}/ca.crt]`,
        `ORDERER_GENERAL_CLUSTER_CLIENTCERTIFICATE=${tls}/server.crt`,
        `ORDERER_GENERAL_CLUSTER_CLIENTPRIVATEKEY=${tls}/server.key`,
        `ORDERER_GENERAL_CLUSTER_ROOTCAS=[${tls}/ca.crt]`,
        ...(net.ports.cluster
          ? [
              "ORDERER_GENERAL_CLUSTER_LISTENADDRESS=0.0.0.0",
              `ORDERER_GENERAL_CLUSTER_LISTENPORT=${clusterPort}`,
              `ORDERER_GENERAL_CLUSTER_SERVERCERTIFICATE=${tls}/server.crt`,
              `ORDERER_GENERAL_CLUSTER_SERVERPRIVATEKEY=${tls}/server.key`,
            ]
          : []),
        // No system channel: the orderer starts empty and is told to join each channel through its admin port.
        "ORDERER_GENERAL_BOOTSTRAPMETHOD=none",
        "ORDERER_CHANNELPARTICIPATION_ENABLED=true",
        "ORDERER_ADMIN_LISTENADDRESS=0.0.0.0:7053",
        "ORDERER_ADMIN_TLS_ENABLED=true",
        `ORDERER_ADMIN_TLS_CERTIFICATE=${tls}/server.crt`,
        `ORDERER_ADMIN_TLS_PRIVATEKEY=${tls}/server.key`,
        `ORDERER_ADMIN_TLS_ROOTCAS=[${tls}/ca.crt]`,
        `ORDERER_ADMIN_TLS_CLIENTROOTCAS=[${tls}/ca.crt]`,
        "ORDERER_ADMIN_TLS_CLIENTAUTHREQUIRED=true",
      ],
      "      ",
    ),
    "    command: orderer",
    "    volumes:",
    ...list([`${base}/msp:/var/hyperledger/orderer/msp:ro`, `${base}/tls:${tls}:ro`, `${o.orderer}:/var/hyperledger/production/orderer`], "      "),
    "    networks: [fabric]",
  ];
};

const couchService = (o) => [
  `  ${o.couch}:`,
  `    container_name: ${o.couch}`,
  `    image: couchdb:${net.fabric.couchdb}`,
  "    restart: unless-stopped",
  "    environment:",
  ...list(["COUCHDB_USER=admin", `COUCHDB_PASSWORD=${secrets.couchdb}`], "      "),
  "    volumes:",
  ...list([`${o.couch}:/opt/couchdb/data`], "      "),
  // Each company's state database can be opened in a browser on this machine, and only from this machine.
  "    ports:",
  `      - "127.0.0.1:${o.couchPort}:5984"`,
  "    networks: [fabric]",
];

const peerService = (o) => {
  const base = `./crypto-config/peerOrganizations/${o.domain}/peers/${o.peer}`;
  return [
    `  ${o.peer}:`,
    `    container_name: ${o.peer}`,
    `    image: hyperledger/fabric-peer:${net.fabric.version}`,
    "    restart: unless-stopped",
    "    environment:",
    ...list(
      [
        "FABRIC_LOGGING_SPEC=INFO",
        "CORE_PEER_TLS_ENABLED=true",
        "CORE_PEER_PROFILE_ENABLED=false",
        "CORE_PEER_TLS_CERT_FILE=/etc/hyperledger/fabric/tls/server.crt",
        "CORE_PEER_TLS_KEY_FILE=/etc/hyperledger/fabric/tls/server.key",
        "CORE_PEER_TLS_ROOTCERT_FILE=/etc/hyperledger/fabric/tls/ca.crt",
        `CORE_PEER_ID=${o.peer}`,
        `CORE_PEER_ADDRESS=${o.peer}:7051`,
        "CORE_PEER_LISTENADDRESS=0.0.0.0:7051",
        `CORE_PEER_CHAINCODEADDRESS=${o.peer}:7052`,
        "CORE_PEER_CHAINCODELISTENADDRESS=0.0.0.0:7052",
        `CORE_PEER_GOSSIP_BOOTSTRAP=${o.peer}:7051`,
        `CORE_PEER_GOSSIP_EXTERNALENDPOINT=${o.peer}:7051`,
        `CORE_PEER_LOCALMSPID=${o.msp}`,
        "CORE_PEER_MSPCONFIGPATH=/etc/hyperledger/fabric/msp",
        "CORE_PEER_GATEWAY_ENABLED=true",
        "CORE_CHAINCODE_EXECUTETIMEOUT=120s",
        // The chaincode runs as a service in its own container. This tells the peer which one is its own.
        `CHAINCODE_AS_A_SERVICE_BUILDER_CONFIG={"peername":"${o.domain}"}`,
        "CORE_LEDGER_STATE_STATEDATABASE=CouchDB",
        `CORE_LEDGER_STATE_COUCHDBCONFIG_COUCHDBADDRESS=${o.couch}:5984`,
        "CORE_LEDGER_STATE_COUCHDBCONFIG_USERNAME=admin",
        `CORE_LEDGER_STATE_COUCHDBCONFIG_PASSWORD=${secrets.couchdb}`,
        "CORE_LEDGER_HISTORY_ENABLEHISTORYDATABASE=true",
      ],
      "      ",
    ),
    "    command: peer node start",
    "    volumes:",
    ...list([`${base}/msp:/etc/hyperledger/fabric/msp:ro`, `${base}/tls:/etc/hyperledger/fabric/tls:ro`, `${o.peer}:/var/hyperledger/production`], "      "),
    // The app's gateway connection for this company comes in here.
    "    ports:",
    `      - "127.0.0.1:${o.peerPort}:7051"`,
    `    depends_on: [${o.couch}]`,
    "    networks: [fabric]",
  ];
};

const caService = (o) => [
  `  ${o.ca}:`,
  `    container_name: ${o.ca}`,
  `    hostname: ${o.ca}`,
  `    image: hyperledger/fabric-ca:${net.fabric.ca}`,
  "    restart: unless-stopped",
  "    environment:",
  ...list(
    [
      "FABRIC_CA_HOME=/etc/hyperledger/fabric-ca-server",
      `FABRIC_CA_SERVER_CA_NAME=ca-${o.code}`,
      "FABRIC_CA_SERVER_PORT=7054",
      "FABRIC_CA_SERVER_TLS_ENABLED=true",
      `REGISTRAR_SECRET=${secrets.registrar}`,
      `CA_CERT=/ca/ca.${o.domain}-cert.pem`,
    ],
    "      ",
  ),
  // The CA signs with the same key that made the company's node certificates, so the people it enrols
  // belong to the same organisation as the company's peer.
  `    command: fabric-ca-server start -b registrar:${secrets.registrar} --ca.certfile /ca/ca.${o.domain}-cert.pem --ca.keyfile /ca/priv_sk --csr.hosts ${o.ca},localhost`,
  "    volumes:",
  ...list(
    [`./crypto-config/peerOrganizations/${o.domain}/ca:/ca:ro`, `${o.ca}:/etc/hyperledger/fabric-ca-server`, `./wallets/${o.code}:/wallet`, "../network/scripts:/scripts:ro"],
    "      ",
  ),
  "    networks: [fabric]",
];

const chaincodeService = (o) => [
  `  ${o.chaincode}:`,
  `    container_name: ${o.chaincode}`,
  `    image: ${net.name}-chaincode:${net.chaincode.version}`,
  "    restart: unless-stopped",
  // chaincode.env holds CHAINCODE_ID, the package ID the peers were given at install.
  "    env_file: ./chaincode/chaincode.env",
  "    environment:",
  ...list(["CHAINCODE_SERVER_ADDRESS=0.0.0.0:9999"], "      "),
  "    networks: [fabric]",
];

const cli = `cli.${net.domain}`;
const volumes = orgs.flatMap((o) => [o.orderer, o.peer, o.couch, o.ca]);

const compose = [
  "# Generated by network/generate.mjs. Start it with `npm run net:up`, not by hand.",
  `name: ${net.name}`,
  "networks:",
  "  fabric:",
  `    name: ${net.name}`,
  "volumes:",
  ...volumes.map((v) => `  ${v}: {}`),
  "services:",
  ...orgs.flatMap((o) => [...ordererService(o), ...couchService(o), ...peerService(o), ...caService(o), ...chaincodeService(o)]),
  `  ${cli}:`,
  `    container_name: ${cli}`,
  `    image: hyperledger/fabric-tools:${net.fabric.version}`,
  "    restart: unless-stopped",
  "    environment:",
  ...list(["FABRIC_LOGGING_SPEC=INFO", "CORE_PEER_TLS_ENABLED=true", "FABRIC_CFG_PATH=/etc/hyperledger/fabric"], "      "),
  "    working_dir: /work",
  "    command: sleep infinity",
  "    volumes:",
  ...list(["./:/work", "../network/scripts:/scripts:ro"], "      "),
  "    networks: [fabric]",
  "",
].join("\n");

/* ------------------------------------------------------------------ net.env: the same facts for the shell scripts */

const quote = (items) => `(${items.map((item) => `"${item}"`).join(" ")})`;
const env = [
  "# Generated by network/generate.mjs. Sourced by the scripts that run inside the containers.",
  `NET_NAME="${net.name}"`,
  `ORGS=${quote(orgs.map((o) => o.code))}`,
  `CHANNELS=${quote(workspaces.map((w) => w.channel))}`,
  `CC_NAME="${cc}"`,
  `CC_VERSION="${net.chaincode.version}"`,
  `CC_SEQUENCE="${net.chaincode.sequence}"`,
  "declare -A ORG_MSP ORG_DOMAIN ORG_PEER ORG_ORDERER ORG_ORDERER_DOMAIN CHANNEL_ORGS",
  ...orgs.flatMap((o) => [
    `ORG_MSP[${o.code}]="${o.msp}"`,
    `ORG_DOMAIN[${o.code}]="${o.domain}"`,
    `ORG_PEER[${o.code}]="${o.peer}"`,
    `ORG_ORDERER[${o.code}]="${o.orderer}"`,
    `ORG_ORDERER_DOMAIN[${o.code}]="${o.ordererDomain}"`,
  ]),
  ...workspaces.map((w) => `CHANNEL_ORGS[${w.channel}]="${w.orgs.join(" ")}"`),
  "",
].join("\n");

/* ------------------------------------------------------------------ network.resolved.json: the same facts for the app */

const resolved = {
  name: net.name,
  domain: net.domain,
  about: net.about,
  fabric: net.fabric.version,
  consensus: net.consensus,
  chaincode: net.chaincode,
  cli,
  appPort: net.ports.app,
  orgs: orgs.map((o) => ({
    code: o.code,
    name: o.name,
    color: o.color,
    msp: o.msp,
    ordererMsp: o.ordererMsp,
    peer: {
      name: o.peer,
      endpoint: `127.0.0.1:${o.peerPort}`,
      tlsCa: `crypto-config/peerOrganizations/${o.domain}/peers/${o.peer}/tls/ca.crt`,
    },
    orderer: o.orderer,
    ordererCluster: `${o.orderer}:${clusterPort}`,
    ca: o.ca,
    chaincode: o.chaincode,
    couchdb: { name: o.couch, url: `http://localhost:${o.couchPort}/_utils/` },
    // The identity the company's app server uses for its own work: watching blocks and checking what its node holds.
    service: {
      cert: `crypto-config/peerOrganizations/${o.domain}/users/User1@${o.domain}/msp/signcerts/User1@${o.domain}-cert.pem`,
      key: `crypto-config/peerOrganizations/${o.domain}/users/User1@${o.domain}/msp/keystore/priv_sk`,
    },
    caCert: `crypto-config/peerOrganizations/${o.domain}/ca/ca.${o.domain}-cert.pem`,
    wallet: `wallets/${o.code}`,
    people: o.people,
  })),
  workspaces: workspaces.map((w) => ({
    channel: w.channel,
    name: w.name,
    about: w.about,
    orgs: w.orgs,
    collections: w.collections.map((c) => ({ name: c.name, orgs: c.orgs })),
  })),
};

fs.mkdirSync(path.join(out, "chaincode"), { recursive: true });
for (const o of orgs) fs.mkdirSync(path.join(out, "wallets", o.code), { recursive: true });
fs.writeFileSync(path.join(out, "crypto-config.yaml"), cryptoConfig);
fs.writeFileSync(path.join(out, "configtx.yaml"), configtx);
fs.writeFileSync(path.join(out, "docker-compose.yaml"), compose);
fs.writeFileSync(path.join(out, "net.env"), env);
for (const w of workspaces) fs.writeFileSync(path.join(out, `collections-${w.channel}.json`), JSON.stringify(collectionsOf(w), null, 2) + "\n");
fs.writeFileSync(path.join(out, "network.resolved.json"), JSON.stringify(resolved, null, 2) + "\n");

const containers = orgs.length * 5 + 1;
console.log(`${orgs.length} companies, ${workspaces.length} channels, ${containers} containers. Files are in .generated/`);
